#!/usr/bin/env bash
# Invoked over SSH by the manual production deployment workflow.
set -Eeuo pipefail
umask 027

release_id="${1:?release id required}"
expected_hash="${2:?archive SHA256 required}"
root=/var/www/caneguard
releases="$root/releases"
shared="$root/shared/api"
current="$root/current"
archive="$releases/.upload-$release_id.tar.gz"
new="$releases/$release_id"
lock="$root/.production-deploy.lock"

if [[ ! "$release_id" =~ ^release-[0-9]+-[a-f0-9]{40}$ ]] ||
   [[ ! "$expected_hash" =~ ^[a-f0-9]{64}$ ]]; then
  echo "Invalid release identity or archive hash" >&2
  exit 1
fi

exec 9>"$lock"
flock -n 9 || { echo "Another deployment is running" >&2; exit 1; }

[[ -L "$current" && -d "$current/api" ]] || { echo "Current release is missing" >&2; exit 1; }
[[ -f "$shared/.env" && -d "$shared/storage" ]] || { echo "Shared Laravel state is missing" >&2; exit 1; }
# The ACL package must be installed on Lightsail before running this workflow.
for tool in setfacl getfacl; do
  command -v "$tool" >/dev/null 2>&1 || {
    echo "Missing $tool on Lightsail; ubuntu must install the 'acl' package" >&2
    exit 1
  }
done
# The scheduler cron below is installed in the deploy user's own crontab.
command -v crontab >/dev/null 2>&1 || {
  echo "Missing crontab on Lightsail; install it as ubuntu with: sudo apt-get install -y cron" >&2
  exit 1
}
[[ "$(systemctl is-enabled cron 2>/dev/null || true)" == enabled ]] && systemctl is-active --quiet cron || {
  echo "The cron service is not enabled and running on Lightsail; enable and start it as ubuntu with: sudo systemctl enable --now cron" >&2
  exit 1
}
[[ -f "$archive" ]] || { echo "Release archive missing" >&2; exit 1; }
[[ ! -e "$new" ]] || { echo "Release already exists" >&2; exit 1; }
printf '%s  %s\n' "$expected_hash" "$archive" | sha256sum -c -

old="$(readlink -f "$current")"
[[ "$old" == "$releases/"* && -d "$old/api" ]] || { echo "Unsafe current symlink" >&2; exit 1; }

activated=0
successful=0
restored=0
restore_previous_release() {
  if [[ "$(cd "$old/api" && php artisan list --raw)" != *"auth:rollback-barrier "* ]]; then
    echo "ERROR: $old predates the rollback barrier; automatic rollback is refused and the new release stays active. Roll back by the operator procedure in docs/production-deployment.md." >&2
    return 1
  fi
  ln -s "$old" "$root/.rollback-$$" || return 1
  mv -Tf "$root/.rollback-$$" "$current" || return 1
}
cleanup() {
  status=$?
  trap - EXIT
  if [[ "$successful" -ne 1 && "$activated" -eq 1 ]]; then
    echo "Health check failed; restoring previous code symlink" >&2
    if restore_previous_release; then
      restored=1
    fi
  fi
  if [[ "$restored" -eq 1 ]]; then
    curl --fail --silent --show-error --max-time 15 https://caneguard.online/api/health || true
    echo "WARNING: Database migrations are not rolled back automatically." >&2
  fi
  rm -f "$archive"
  exit "$status"
}
trap cleanup EXIT

mkdir "$new"
tar -xzf "$archive" --no-same-owner --no-same-permissions -C "$new"
[[ -s "$new/api/public/index.php" && -s "$new/api/public/index.html" ]] ||
  { echo "Incomplete release archive" >&2; exit 1; }
[[ ! -e "$new/api/.env" ]] || { echo "Archive contains an unexpected api/.env" >&2; exit 1; }

ln -s "$shared/.env" "$new/api/.env"
rm -rf "$new/api/storage"
ln -s "$shared/storage" "$new/api/storage"
cd "$new/api"
composer install --no-dev --no-interaction --no-progress --prefer-dist --optimize-autoloader
php artisan config:clear
php artisan route:clear
php artisan view:clear
php artisan event:clear
php artisan config:cache
php artisan view:cache

# Composer may extract 0640 deploy:deploy files despite setgid parents.
# Add PHP-FPM read/traverse access without broad other-read permissions or
# requiring deploy to change ownership/group. Host ACL inheritance is a baseline.
# -P prevents following shared .env/storage symlinks into persistent state.
setfacl -R -P -m u:www-data:rX "$new"

# Evaluate effective POSIX access as the FPM UID/groups, including ancestors,
# shared symlink targets and files generated by config:cache/view:cache above.
# Read-only metadata validation needs neither sudo nor changes to shared state.
# Any failure exits before migrations or activation; HTTP readiness stays below.
php "$new/scripts/verify-release-access.php" "$new"

# Flag-aware: a no-op unless the shared .env enables aerial analysis. When it
# does, Python, packages, the pinned model, storage and one smoke inference
# must pass here, before migrations and activation, or the deploy fails
# instead of shipping uploads that answer 503.
php "$new/scripts/preflight-aerial.php" "$new"

# Only non-destructive, backward-compatible migrations may be released.
# Take an out-of-band MySQL backup before deployments with schema changes.
php artisan migrate --force --no-interaction

# Idempotent: creates the pilot district and first admin from the shared .env
# only when missing, and writes security audit rows for what it creates.
php artisan caneguard:bootstrap --no-interaction

# Ensure the deploy user's cron runs the Laravel scheduler (reminders, follow-up
# notifications and the prune commands). The entry targets the stable current
# symlink, so later releases need no change. Earlier entries for that symlink are
# replaced, unrelated jobs are kept, and re-running is a no-op.
cron_line="* * * * * cd $current/api && $(command -v php) artisan schedule:run >> /dev/null 2>&1 # caneguard-scheduler"
if ! cron_existing="$(crontab -l 2>&1)"; then
  case "$cron_existing" in
    "no crontab for "*) cron_existing="" ;;
    *) echo "Cannot read the deploy user's crontab; nothing was changed: $cron_existing" >&2; exit 1 ;;
  esac
fi
cron_next="$(printf '%s\n' "$cron_existing" | awk \
  -v prefix="* * * * * cd $current/api && " -v line="$cron_line" '
  function norm(s) { gsub(/[ \t]+/, " ", s); gsub(/ *>+ */, ">", s); sub(/^ /, "", s); sub(/ $/, "", s); return s }
  { entry = norm($0) }
  entry == "" || (index(entry, prefix) == 1 && entry ~ /artisan schedule:run>\/dev\/null 2>&1( # caneguard-scheduler)?$/) { next }
  { print }
  END { print line }')"
if [[ "$cron_next" != "$cron_existing" ]]; then
  printf '%s\n' "$cron_next" | crontab -
  echo "Installed scheduler cron for deploy"
fi
php artisan caneguard:record-scheduler-install "$cron_line" --no-interaction
php artisan auth:backfill-onboarding

php artisan auth:rollback-barrier on
ln -s "$new" "$root/.activate-$$"
mv -Tf "$root/.activate-$$" "$current"
activated=1

php artisan up

# Ensure public API and SPA both respond through the activated Nginx root.
health="$(curl --fail --silent --show-error --max-time 20 https://caneguard.online/api/health)"
HEALTH_JSON="$health" php -r '
$body = json_decode(getenv("HEALTH_JSON"), true);
if (($body["data"]["status"] ?? null) !== "ok" ||
    ($body["data"]["checks"]["database"] ?? null) !== "ready" ||
    ($body["data"]["checks"]["storage"] ?? null) !== "ready") {
    fwrite(STDERR, "API readiness failed".PHP_EOL);
    exit(1);
}'
root_shell="$(curl --fail --silent --show-error --max-time 20 https://caneguard.online/)"
grep -qi '<html' <<<"$root_shell"
# A static index served by Nginx bypasses the per-response CSP nonce substitution.
if grep -q '__CSP_NONCE__' <<<"$root_shell"; then
  echo "SPA shell served without a CSP nonce" >&2
  exit 1
fi
php artisan auth:rollback-barrier off
successful=1
echo "PASS: Active release $release_id"
echo "Rollback reference: $old"
