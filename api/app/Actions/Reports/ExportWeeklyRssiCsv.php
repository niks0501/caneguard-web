<?php

namespace App\Actions\Reports;

/**
 * Renders the weekly RSSI export as a CSV an office staff member can open,
 * check, and attach to an email to the SRA by hand.
 *
 * The file opens with a summary block, then one case table. Every row names its
 * section, so validated and suspected cases stay distinguishable and a
 * suspected case can never be read as part of the validated totals.
 */
final class ExportWeeklyRssiCsv
{
    public const HEADERS = [
        'report_section',
        'case_reference',
        'submitted_date',
        'barangay',
        'staff_classification',
        'verification_outcome',
        'reported_affected_area_hectares',
        'area_measurement',
    ];

    /**
     * @param  array<string, mixed>  $report
     */
    public function handle(array $report): string
    {
        $output = fopen('php://temp', 'wb+');
        if ($output === false) {
            return '';
        }

        foreach ($this->summary($report) as $line) {
            fputcsv($output, array_map($this->neutralizeSpreadsheetFormula(...), $line));
        }
        fputcsv($output, []);
        fputcsv($output, self::HEADERS);

        foreach ([BuildWeeklyRssiReport::SECTION_VALIDATED, BuildWeeklyRssiReport::SECTION_SUSPECTED] as $section) {
            foreach ($report['sections'][$section]['rows'] as $row) {
                fputcsv($output, array_map($this->neutralizeSpreadsheetFormula(...), [
                    $row['section'],
                    $row['case_reference'],
                    $row['submitted_date'],
                    $row['barangay'],
                    $row['staff_classification'],
                    $row['verification_outcome'],
                    $row['area_hectares'] ?? '',
                    $row['area_measurement'],
                ]));
            }
        }

        rewind($output);
        $csv = (string) stream_get_contents($output);
        fclose($output);

        return $csv;
    }

    /**
     * @param  array<string, mixed>  $report
     * @return array<int, array<int, string>>
     */
    private function summary(array $report): array
    {
        $validated = $report['sections'][BuildWeeklyRssiReport::SECTION_VALIDATED];
        $suspected = $report['sections'][BuildWeeklyRssiReport::SECTION_SUSPECTED];
        $district = $report['district'];

        return [
            ['Weekly RSSI report'],
            ['District', $district === null ? 'Not available' : $district['name'].' ('.$district['code'].')'],
            ['Reporting period', $report['period']['from'].' to '.$report['period']['to'].', '.$report['period']['timezone']],
            ['Generated', $report['generated_at']],
            ['Generated by', $report['generated_by']],
            ['Validated cases', (string) $validated['cases']],
            ['Validated barangays', (string) $validated['barangays']],
            ['Reported affected area of validated cases (hectares)', number_format((float) $validated['reported_area_hectares'], 2, '.', '')],
            ['Area note', (string) $validated['area_method']],
            ['Suspected cases, excluded from validated totals', (string) $suspected['cases']],
            ['Suspected barangays', (string) $suspected['barangays']],
            ['Farmer and farm names', 'Not included'],
            ['Infestation percentage', (string) $report['omitted_metrics'][0]['reason']],
            ['Method', (string) $report['method']['confirmation']],
        ];
    }

    private function neutralizeSpreadsheetFormula(mixed $value): mixed
    {
        if (! is_string($value) || $value === '') {
            return $value;
        }

        return in_array($value[0], ['=', '+', '-', '@', "\t", "\r", "\n"], true)
            ? "'".$value
            : $value;
    }
}
